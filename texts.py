def _pluralize_friends(count: int) -> str:
    """Возвращает 'друг' / 'друга' / 'друзей' в правильном падеже под число."""
    if count % 10 == 1 and count % 100 != 11:
        return "друг"
    if count % 10 in (2, 3, 4) and count % 100 not in (12, 13, 14):
        return "друга"
    return "друзей"


def referral_tiers_text() -> str:
    lines = []
    for tier in REFERRAL_TIERS:
        word = _pluralize_friends(tier["count"])
        lines.append(f"• {tier['count']} {word} → {tier['reward']}")
    return "\n".join(lines)
